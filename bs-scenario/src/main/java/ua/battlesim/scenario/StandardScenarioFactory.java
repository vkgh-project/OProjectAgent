package ua.battlesim.scenario;

import ua.battlesim.api.NavGrid;
import ua.battlesim.api.RoundSetup;
import ua.battlesim.api.ScenarioFactory;
import ua.battlesim.api.Side;
import ua.battlesim.api.SimConfig;
import ua.battlesim.api.Terrain;
import ua.battlesim.api.TerrainService;
import ua.battlesim.api.UnitData;
import ua.battlesim.api.UnitInfo;
import ua.battlesim.api.UnitState;
import ua.battlesim.api.UnitType;
import ua.battlesim.api.WeatherFactory;
import ua.battlesim.api.WeatherModel;
import ua.battlesim.math.DetRandom;

import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

/**
 * The standard deterministic scenario factory.
 *
 * <p>For {@code (masterSeed, roundNumber)} the factory always builds the same
 * {@link RoundSetup}: the same round seed, the same terrain (generated by the
 * injected {@link TerrainService} from the round seed), the same units and
 * the same weather. Only {@link DetRandom} (bs-math) is consulted and
 * {@link StrictMath} is used for trigonometry — no wall clock, no unseeded
 * randomness, no hash-order dependence.
 *
 * <p>Round seed: the first value of the SplitMix64 generator seeded with
 * {@code masterSeed + roundNumber x 0x9E3779B97F4A7C15} (the golden-ratio
 * step constant of {@link DetRandom}).
 *
 * <p>Units: BLUE is built before RED (ids are ascending: BLUE ids
 * {@code 0..b-1}, RED ids {@code b..b+r-1}); each side gets
 * {@code minUnits..maxUnits} units of uniformly random {@link UnitType}.
 * BLUE spawns only in the northern 35% of the map, RED only in the southern
 * 35%, both with a 120 m east/west margin (clamped to {@code size / 2} on
 * maps smaller than 240 m so the band is never empty). A candidate position
 * is accepted only when its navigation cell is passable and belongs to the
 * main connected component, the unit's circle plus a 1 m clearance fits on
 * passable cells ({@link NavGrid#walkable}), and every already placed
 * footprint is at least 4 m away (centre distance at least
 * {@code 4 m + radius + otherRadius}). Random sampling (64 attempts per
 * unit) falls back to a deterministic 2 m grid scan of the spawn band.
 *
 * <p>Units start {@code READY} with 100 health, zero cooldown and odometer,
 * not destroyed, heading and aim toward the enemy side: {@code +pi/2}
 * (south, +z) for BLUE and {@code -pi/2} (north, -z) for RED.
 *
 * <p>Weather: the injected {@link WeatherFactory} creates the round's
 * weather model, seeded from the round seed (bs-scenario never depends on a
 * concrete weather module); with {@code SimConfig.weatherEnabled == false}
 * the factory is expected to keep the model permanently clear. Each
 * {@link #create} call asks the factory for a fresh model, so rounds and
 * engines never share one.
 *
 * <p>Units: metres, seconds and radians throughout; x east, z south.
 *
 * <p>Thread-safety: {@link #create} is a pure function of its arguments and
 * the injected collaborators; it may be called from the single worker thread
 * that generates the next round.
 */
public final class StandardScenarioFactory implements ScenarioFactory {

    /** SplitMix64 step constant (the golden ratio), as in {@link DetRandom}. */
    static final long GOLDEN_RATIO = 0x9E3779B97F4A7C15L;

    /** Fixed salt that separates the unit stream from other round streams. */
    static final long SALT_UNITS = 0x5C7D6B5A6B7B8A91L;

    /** Fixed salt that derives the weather seed from the round seed. */
    static final long SALT_WEATHER = 0x9E2B1C4D8F6A7B35L;

    /** Fraction of the map each side may spawn in (BLUE: north, RED: south). */
    static final double BAND_FRACTION = 0.35;

    /** East/west spawn margin in metres (120 m per the standard rules). */
    static final double SIDE_MARGIN_METRES = 120.0;

    /** Extra clearance in metres added to the radius for the walkable check. */
    static final double WALK_MARGIN_METRES = 1.0;

    /** Minimum metres between two unit footprints (edge to edge). */
    static final double FOOTPRINT_GAP_METRES = 4.0;

    /** Random candidate positions tried per unit before the grid scan. */
    static final int RANDOM_ATTEMPTS_PER_UNIT = 64;

    /** Step of the deterministic fallback scan of the spawn band, in metres. */
    static final double SCAN_STEP_METRES = 2.0;

    private final TerrainService terrainService;
    private final SimConfig config;
    private final WeatherFactory weatherFactory;

    /**
     * @param terrainService the injected terrain generator (non-null)
     * @param config         the round configuration (non-null)
     * @param weatherFactory the injected weather model factory (non-null)
     */
    public StandardScenarioFactory(TerrainService terrainService, SimConfig config,
            WeatherFactory weatherFactory) {
        this.terrainService = Objects.requireNonNull(terrainService, "terrainService");
        this.config = Objects.requireNonNull(config, "config");
        this.weatherFactory = Objects.requireNonNull(weatherFactory, "weatherFactory");
    }

    /** @return the injected terrain service */
    public TerrainService terrainService() {
        return terrainService;
    }

    /** @return the round configuration */
    public SimConfig config() {
        return config;
    }

    /** @return the injected weather model factory */
    public WeatherFactory weatherFactory() {
        return weatherFactory;
    }

    @Override
    public RoundSetup create(long masterSeed, int roundNumber) {
        if (roundNumber < 1) {
            throw new IllegalArgumentException("roundNumber must be >= 1: " + roundNumber);
        }
        long roundSeed = new DetRandom(masterSeed + (long) roundNumber * GOLDEN_RATIO).nextLong();
        Terrain terrain = Objects.requireNonNull(
                terrainService.generate(roundSeed), "terrain for seed " + roundSeed);
        NavGrid nav = Objects.requireNonNull(terrain.nav(), "nav grid");
        double size = terrain.size();

        DetRandom rng = new DetRandom(roundSeed).fork(SALT_UNITS);
        List<UnitData> units = new ArrayList<>();
        for (Side side : List.of(Side.BLUE, Side.RED)) {
            int count = config.minUnits() + rng.nextInt(config.maxUnits() - config.minUnits() + 1);
            for (int k = 0; k < count; k++) {
                UnitType type = UnitType.values()[rng.nextInt(UnitType.values().length)];
                double radius = UnitInfo.of(type).radius();
                double[] pos = place(side, rng, nav, size, radius, units);
                double heading = side == Side.BLUE ? StrictMath.PI / 2.0 : -StrictMath.PI / 2.0;
                units.add(new UnitData(units.size(), side, type, pos[0], pos[1],
                        heading, heading, 100, UnitState.READY, 0, 0.0, -1));
            }
        }

        WeatherModel weather = weatherFactory.create(
                new DetRandom(roundSeed).fork(SALT_WEATHER).nextLong(), config);
        return new RoundSetup(roundNumber, roundSeed, terrain, units, weather);
    }

    /**
     * Finds a valid spawn position for one unit of the given side and radius,
     * deterministic in the given generator state and the already placed units.
     *
     * @param side   the owning side (decides the spawn band)
     * @param rng    the deterministic unit stream (mutated on random sampling)
     * @param nav    the round navigation grid
     * @param size   the map side length in metres
     * @param radius the unit radius in metres
     * @param placed the units placed so far (both sides)
     * @return the chosen position as {@code {x, z}} in metres
     * @throws IllegalStateException if the spawn band holds no valid position
     */
    private static double[] place(Side side, DetRandom rng, NavGrid nav, double size,
            double radius, List<UnitData> placed) {
        double zMin = side == Side.BLUE ? 0.0 : size * (1.0 - BAND_FRACTION);
        double zMax = side == Side.BLUE ? size * BAND_FRACTION : size;
        double margin = StrictMath.min(SIDE_MARGIN_METRES, size / 2.0);
        double xMin = margin;
        double xMax = size - margin;
        double clearance = radius + WALK_MARGIN_METRES;

        for (int attempt = 0; attempt < RANDOM_ATTEMPTS_PER_UNIT; attempt++) {
            double x = xMin + rng.nextDouble() * (xMax - xMin);
            double z = zMin + rng.nextDouble() * (zMax - zMin);
            if (valid(nav, x, z, clearance, radius, placed)) {
                return new double[] { x, z };
            }
        }
        // deterministic fallback: scan the whole band on a fixed 2 m grid
        for (double z = zMin; z <= zMax; z += SCAN_STEP_METRES) {
            for (double x = xMin; x <= xMax; x += SCAN_STEP_METRES) {
                if (valid(nav, x, z, clearance, radius, placed)) {
                    return new double[] { x, z };
                }
            }
        }
        throw new IllegalStateException("no valid spawn position found for side "
                + side + " on a " + size + " m map");
    }

    /**
     * A candidate position is valid when it lies in the main nav component,
     * the unit's footprint plus 1 m clearance fits on passable cells, and all
     * placed footprints are at least 4 m away.
     */
    private static boolean valid(NavGrid nav, double x, double z,
            double clearance, double radius, List<UnitData> placed) {
        int cells = nav.cells();
        int i = cell(x, nav.cellSize(), cells);
        int j = cell(z, nav.cellSize(), cells);
        if (!nav.passable(i, j) || nav.component(i, j) != nav.mainComponent()) {
            return false;
        }
        if (!nav.walkable(x, z, clearance)) {
            return false;
        }
        for (UnitData u : placed) {
            double dx = u.x() - x;
            double dz = u.z() - z;
            double need = FOOTPRINT_GAP_METRES + radius + UnitInfo.of(u.type()).radius();
            if (dx * dx + dz * dz < need * need) {
                return false;
            }
        }
        return true;
    }

    /** Maps metres to a clamped grid index, deterministic for the same input. */
    private static int cell(double v, double cellSize, int cells) {
        int idx = (int) StrictMath.floor(v / cellSize);
        if (idx < 0) {
            return 0;
        }
        if (idx >= cells) {
            return cells - 1;
        }
        return idx;
    }
}
